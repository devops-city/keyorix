#!/usr/bin/env python3
"""Regenerate scripts/ci-test-weights.tsv from measured per-test times.

The test-suite matrix splits one big package across several legs by test name
(scripts/ci-test-legs.sh, weighted_run_filter). The split only affects BALANCE,
never completeness: every test lands in exactly one shard whatever the weights
say (assert_all_shards_complete proves it on every PR). This script keeps the
balance honest. Two kinds of input:

  * `go test -json` output, one file per package (any run, e.g. local):
        go test -json -count=1 ./internal/core > core.json
        python3 scripts/ci/gen-test-weights.py core.json http.json > scripts/ci-test-weights.tsv

  * `go test -v` text for a named package, which includes a CI job log
    (`kgh run view --job <id> --log`, a leg run with -v): lines such as
    `--- PASS: TestName (12.34s)` at top level. Several legs of one package
    pass the same --v-log name several times:
        python3 scripts/ci/gen-test-weights.py \\
            --v-log internal/core=core-1.log --v-log internal/core=core-2.log

Rows: <package path relative to the module>\t<top-level test name>\t<weight>.
A test listed here weighs its elapsed seconds; every test NOT listed weighs the
package's `*` row (the mean of the unlisted tests when the file was generated),
so a newly added test is placed as an average test until the file is regenerated.
Only tests of at least MIN_SECONDS are listed, which keeps the file small.

CI times are the right unit (the race detector and the runner change the
ranking of small vs. large tests); a local run is a good ranking of the heavy
tests but under-weights the many small ones. `--default-scale pkg=K` multiplies
that package's `*` row by K to calibrate a local run against one measured CI run;
the factor used is printed as a comment so the next regeneration can repeat it.

Parallel tests (t.Parallel) are timed from their resume, so a package whose
tests are all parallel gets near-uniform weights; there the split degrades to
an even spread by name, which is what that kind of package wants.
"""
import argparse
import json
import re

MODULE = "github.com/keyorixhq/keyorix/"
MIN_SECONDS = 3.0
V_LINE = re.compile(r"(?:^|Z )--- (PASS|FAIL|SKIP): ([^\s/]+) \(([0-9.]+)s\)")


def load_json(paths):
    elapsed = {}  # package -> {test: seconds}
    for path in paths:
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                try:
                    ev = json.loads(line)
                except ValueError:
                    continue
                test = ev.get("Test")
                if not test or "/" in test:
                    continue
                if ev.get("Action") not in ("pass", "fail", "skip"):
                    continue
                pkg = ev["Package"].removeprefix(MODULE)
                elapsed.setdefault(pkg, {})[test] = float(ev.get("Elapsed", 0.0))
    return elapsed


def load_v(items, elapsed):
    for item in items:
        pkg, _, path = item.partition("=")
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = V_LINE.search(line)
                if m:
                    elapsed.setdefault(pkg, {})[m.group(2)] = float(m.group(3))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("json", nargs="*", help="`go test -json` output files")
    ap.add_argument("--v-log", action="append", default=[], metavar="PKG=FILE",
                    help="`go test -v` text (or a CI job log) for PKG (module-relative path)")
    ap.add_argument("--default-scale", action="append", default=[], metavar="PKG=K",
                    help="multiply PKG's `*` default weight by K (calibration)")
    args = ap.parse_args()
    if not args.json and not args.v_log:
        ap.error("give at least one `go test -json` file or --v-log PKG=FILE")
    scale = {}
    for item in args.default_scale:
        pkg, _, k = item.partition("=")
        scale[pkg] = float(k)

    elapsed = load_json(args.json)
    load_v(args.v_log, elapsed)
    print("# Generated by scripts/ci/gen-test-weights.py; see that script's header.")
    print("# Format: <package>\\t<test>\\t<weight seconds>. `*` is the weight of every test not listed.")
    for pkg in sorted(elapsed):
        tests = elapsed[pkg]
        heavy = {t: s for t, s in tests.items() if s >= MIN_SECONDS}
        rest = [s for t, s in tests.items() if t not in heavy]
        default = max(sum(rest) / len(rest), 0.001) if rest else 0.001
        k = scale.get(pkg, 1.0)
        if k != 1.0:
            print(f"# {pkg}: `*` row multiplied by {k} (--default-scale)")
        print(f"{pkg}\t*\t{default * k:.4f}")
        for t, s in sorted(heavy.items(), key=lambda kv: (-kv[1], kv[0])):
            print(f"{pkg}\t{t}\t{s:.1f}")


if __name__ == "__main__":
    main()
