#!/usr/bin/env bash
# scripts/ci-test-legs.sh — single source of truth for which Go packages each
# CI test-suite matrix leg (.github/workflows/ci.yml) runs, and which packages
# are deliberately excluded from every leg, with a reason.
#
# G80 campaign, C5: before this file existed, the exclusion patterns lived
# only as bare `grep -v` flags in ci.yml with a comment pointing at
# `git log -S` for the reason -- exactly the shape that let server/http sit
# excluded, with no leg anywhere, for ~4 months, invisible to anyone not
# already reading that file's history. This file is sourced by BOTH the
# test-suite matrix step and the leg-completeness assertion job, so the two
# can never silently drift apart -- a package pinned to a leg here is pinned
# for both; a pattern excluded here is excluded for both.
#
# Not executable on its own: `source` this file, then call its functions.

# exclusion_entries: one per line, pipe-delimited:
#   <go-list-suffix-regex>|<kind>|<reason>|<issue>|<date-added:YYYY-MM-DD>
#
# kind is one of:
#   TEMPORARY -- a real gap meant to close. Subject to the 30-day freshness
#     check in ci.yml: an entry older than 30 days fails CI outright, so a
#     stale exclusion cannot simply sit forever unnoticed the way the
#     pre-C5 bare grep -v list did.
#   PERMANENT -- structurally correct forever (generated code with nothing
#     to test). No fix will ever "land" for this, so it is exempt from the
#     freshness check.
#   SHARDED -- NOT a coverage gap. The package runs, just via its own
#     dedicated matrix leg(s) below (server/http/handlers -> handlers-1..4)
#     rather than through root_base()'s catch-all. Excluded from root_base's
#     package list (so it isn't ALSO run there, doubling the work) but
#     included back into the completeness union via its dedicated leg(s).
#     Exempt from the freshness check for the same reason as PERMANENT: it
#     is not a gap to close.
#
# date-added is when an entry was captured in THIS structured, enforced
# table -- not necessarily when the underlying exclusion was first added to
# ci.yml. The three TEMPORARY entries below trace back to a bare `grep -v`
# added 2026-04-27 (commit 7ccb7dda) -- see their linked issues for that
# history -- but are dated here 2026-08-23, the day this ratchet was
# introduced (G80 C5). Back-dating them to 2026-04-27 would fail the
# freshness check on the PR that introduces the check itself, which is not
# the failure mode this check exists to catch (a NEW exclusion sitting
# unreviewed for 30+ days going forward); the ~4-month-old debt itself is
# not hidden -- it's on record in #1533/#1534/#1535 and in this comment.
#
# server/proto/pb$ PERMANENT entry REMOVED 2026-08-28 (#1541): its own
# justification ("auto-generated protobuf code, no tests to write") was
# asserted, not verified. server/proto/pb/generated_code_test.go now
# machine-checks the real claim -- every non-test .go file in that package
# carries a genuine "Code generated by ... DO NOT EDIT." header -- which is
# strictly stronger than #1541's own originally-proposed "zero *_test.go
# files" check (a hand-written non-test file, e.g. a custom marshaler, would
# slip through that weaker check while genuinely breaking the exemption's
# premise). Adding that test means the package no longer has "no tests to
# write" -- it has exactly one, and a meaningful one -- so the PERMANENT,
# never-run-in-CI exclusion no longer applies: the package now falls through
# to root_base()'s normal catch-all (root-4) like any other package, and its
# one real test runs there.
exclusion_entries() {
  cat <<'EOF'
server/http$|SHARDED|runs in its own dedicated http-1..6 matrix legs below (G80 C4, 2026-08-23) -- see #1535 for the ~4-month exclusion history this closes|#1535|2026-08-23
server/http/handlers$|SHARDED|runs in its own dedicated handlers-1..4 matrix legs below|n/a|2026-04-27
EOF
}

# coverage_floor_exclusions: SAME shape and discipline as exclusion_entries()
# above (pipe-delimited <pattern>|<kind>|<reason>|<issue>|<date-added>, kind
# TEMPORARY/PERMANENT, TEMPORARY subject to the same 30-day freshness check),
# but a DIFFERENT axis: exclusion_entries() controls whether a PACKAGE runs in
# any CI leg at all; this controls whether coverage.out LINES matching
# <pattern> (a package that DOES run) are filtered out of the coverage-FLOOR
# sum specifically ("Merge coverage profiles", ci.yml). A package excluded
# here still runs, still gets tested, still gets its own coverage.out lines --
# those lines are just not counted toward the floor. A package excluded via
# exclusion_entries() never reaches coverage.out in the first place, so an
# entry here for it would be inert -- the two tables are disjoint by
# construction, not by convention.
#
# server/proto/pb's *.pb.go PERMANENT entry replaces what was, before this
# table existed, only a bare `grep -v '\.pb\.go:'` in ci.yml with a prose
# comment restating the reasoning inline (added alongside #1541, G80 Wave 1,
# 2026-08-25) -- the exact "asserted, not machine-checked" shape #1541's own
# comment above criticizes scripts/ci-test-legs.sh for having FIXED, applied
# here to itself: the reasoning now lives in one enforced place instead of a
# comment nobody re-reads.
coverage_floor_exclusions() {
  cat <<'EOF'
\.pb\.go:|PERMANENT|generated protobuf/gRPC code (protoc-gen-go/protoc-gen-go-grpc), ~16.7k lines, ~0% covered by design -- its one real test (server/proto/pb/generated_code_test.go's TestEveryFileIsGenerated) checks file headers, not the generated marshal/unmarshal/gRPC logic itself; same principle gosec's own -exclude-generated flag already applies to this same package|#1541|2026-08-25
internal/faultstorage/faulty_storage_generated\.go:|PERMANENT|generated fault-injection wrapper (internal/faultstorage/gen, `// Code generated ... DO NOT EDIT.`), ~3.8k statements of one-line pass-through methods that exist only so tests can inject storage faults; ~1% covered by design -- correctness of the generator is proven by generated_fresh_test.go (output matches the generator) and gen's own tests, not by exercising every wrapper. Counted only since Go 1.27.2 fixed coverage statement weights (#2893), which exposed it as 3.8k of the floor's 34.7k statements|#2893|2026-10-09
EOF
}

# coverage_floor_grep_patterns: just the regex column, for ci.yml's "Merge
# coverage profiles" step to build its `grep -v` args from -- so the pattern
# lives in exactly one place instead of the registry and the grep flag
# drifting apart.
coverage_floor_grep_patterns() {
  coverage_floor_exclusions | cut -d'|' -f1
}

# check_coverage_floor_exclusion_freshness: same discipline as
# check_exclusion_freshness below, applied to coverage_floor_exclusions
# instead of exclusion_entries.
check_coverage_floor_exclusion_freshness() {
  local today_epoch failed=0
  today_epoch=$(date -u -d "$(date -u +%Y-%m-%d)" +%s)
  while IFS='|' read -r pattern kind reason issue added; do
    [ "$kind" = "TEMPORARY" ] || continue
    local added_epoch age_days
    added_epoch=$(date -u -d "$added" +%s)
    age_days=$(( (today_epoch - added_epoch) / 86400 ))
    if [ "$age_days" -gt 30 ]; then
      echo "STALE COVERAGE-FLOOR EXCLUSION (${age_days}d > 30d budget): $pattern -- $reason ($issue, added $added)"
      failed=1
    fi
  done < <(coverage_floor_exclusions)
  return $failed
}

# exclusion_patterns: just the regex column, one per line -- the set of
# patterns root_base() excludes from the root/core legs entirely (every kind:
# a SHARDED package must not ALSO run via root_base's catch-all, even though
# it runs elsewhere).
exclusion_patterns() {
  exclusion_entries | cut -d'|' -f1
}

# never_run_patterns: exclusion_patterns filtered to kinds that mean "this
# package runs in NO leg, anywhere" (TEMPORARY, PERMANENT) -- excludes
# SHARDED, which does run, just not via root_base. This is the set the
# leg-completeness assertion subtracts from `go list ./...`.
never_run_patterns() {
  exclusion_entries | awk -F'|' '$2 != "SHARDED" { print $1 }'
}

# root_base: every package eligible for the root-N/core legs -- go list
# minus every exclusion pattern (all kinds; a SHARDED package must not
# double-run here even though it's covered elsewhere).
root_base() {
  local args=()
  while IFS= read -r pattern; do
    args+=(-e "$pattern")
  done < <(exclusion_patterns)
  go list ./... | grep -v "${args[@]}"
}

