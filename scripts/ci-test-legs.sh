# run_filter_for_shard: builds a `go test -run` regex selecting roughly 1/N
# of a single package's top-level tests, by (sorted test name index) mod N --
# the mechanism handlers-1..4 already uses. Shared here so any future
# by-test-name-sharded leg (not just handlers) reuses the identical, already-
# proven splitting logic instead of a second hand-copied implementation.
run_filter_for_shard() {
  local pkg="$1" shard="$2" n="$3"
  local names selected
  # '^(Test|Fuzz)', not '^Test' (2026-09-27): with -run restricted to Test*
  # names, every sharded package's Fuzz* seed corpora (testdata/fuzz + f.Add
  # seeds, which `go test` runs as ordinary regression tests) silently never
  # ran in this matrix -- server/http, server/http/handlers and
  # internal/storage/store included. fuzz-targets only checks registration.
  names=$(go test -list '^(Test|Fuzz)' "$pkg" | grep -v '^ok\b' | sort)
  selected=$(echo "$names" | awk -v n="$n" -v s="$shard" 'NR % n == (s - 1)')
  printf '^(%s)$' "$(echo "$selected" | paste -sd '|' -)"
}

# check_exclusion_freshness: fails (nonzero exit, one line per offender on
# stdout) if any TEMPORARY exclusion_entries row is more than 30 days old.
# PERMANENT/SHARDED rows are exempt -- there is no fix to land for either, so
# "how long has this sat here" is not a meaningful signal for them. This is
# deliberately a hard failure, not a warning: a warning is exactly what the
# pre-C5 bare `grep -v` list amounted to in practice (a comment nobody
# re-reads), which is how server/http sat excluded with no leg for ~4 months
# unnoticed.
check_exclusion_freshness() {
  local today_epoch failed=0
  today_epoch=$(date -u -d "$(date -u +%Y-%m-%d)" +%s)
  while IFS='|' read -r pattern kind reason issue added; do
    [ "$kind" = "TEMPORARY" ] || continue
    local added_epoch age_days
    added_epoch=$(date -u -d "$added" +%s)
    age_days=$(( (today_epoch - added_epoch) / 86400 ))
    if [ "$age_days" -gt 30 ]; then
      echo "STALE EXCLUSION (${age_days}d > 30d budget): $pattern -- $reason ($issue, added $added)"
      failed=1
    fi
  done < <(exclusion_entries)
  return $failed
}

# assert_leg_completeness: fails (nonzero exit, listing every offending
# package on stdout) if any package in `go list ./...` is covered by NEITHER
# the exclusion table (never_run_patterns -- TEMPORARY/PERMANENT only; a
# SHARDED package must still be covered by its own leg to pass) NOR any CI
# test-suite leg's package list. This is the guard against a package
# silently landing in zero legs, the exact failure mode that let
# server/http go untested for ~4 months with nothing red anywhere.
assert_leg_completeness() {
  local never_args=()
  while IFS= read -r p; do never_args+=(-e "$p"); done < <(never_run_patterns)
  local target actual missing
  target=$(go list ./... | grep -v "${never_args[@]}" | sort -u)
  actual=$(
    while IFS= read -r leg; do
      pkgs_for_leg "$leg"
    done < <(all_leg_names) | sort -u
  )
  missing=$(comm -23 <(echo "$target") <(echo "$actual"))
  if [ -n "$missing" ]; then
    echo "The following package(s) are covered by NO CI test-suite leg and are not in the exclusion table (scripts/ci-test-legs.sh):"
    echo "$missing"
    return 1
  fi
  echo "OK: every non-excluded package is covered by at least one CI test-suite leg."
  return 0
}

# assert_pinned_leg_packages_valid: for every package explicitly pinned to
# root-1/2/3/core/storage-store (as opposed to root-4's dynamic catch-all)
# plus the two single-package sharded targets (handlers_pkg, http_pkg),
# assert (a) it still exists in `go list ./...` right now, and (b) among the
# root-1/2/3/core/storage-store group, it is pinned to exactly one leg.
#
# This is deliberately a DIFFERENT check from assert_leg_completeness above:
# completeness only asks whether every `go list` package is covered by
# *something* -- a stale pinned entry for a package that no longer exists is
# invisible to it, because removing/renaming a package just means one fewer
# thing needs covering, not a gap. That is exactly the FINISH-SPLIT-step-2
# class of break (#2076, 2026-09-25): PR #2076 moved internal/trust ->
# pkg/trust; root_2_pkgs() still pinned the old path; assert_leg_completeness
# stayed green (pkg/trust fell through to root-4's catch-all uncontested,
# and nothing was left uncovered) while the merge_group full tier's actual
# `go test $(pkgs_for_leg root-2)` failed outright with "no required module
# provides package .../internal/trust" -- twice, on two separate queued
# commits, because nothing before the merge queue could have caught it.
#
# Independent of test execution -- only needs `go list`, so it runs in the
# same fast pre-test-suite job as assert_leg_completeness, on every PR, not
# just once the merge queue actually invokes the stale pin.
assert_pinned_leg_packages_valid() {
  local actual failed=0
  actual=$(go list ./... | sort -u)

  local -a exclusive_lists=(root_1_pkgs root_2_pkgs root_3_pkgs core_pkgs storage_store_pkgs encryption_pkgs faultops_pkgs)
  local list_name pkg
  local pinned_pkg_names="" pinned_pkg_owners=""

  for list_name in "${exclusive_lists[@]}"; do
    while IFS= read -r pkg; do
      [ -n "$pkg" ] || continue
      if ! grep -qxF "$pkg" <<<"$actual"; then
        echo "STALE PINNED PACKAGE: $list_name lists '$pkg', which does not exist in \`go list ./...\` (renamed or deleted?)"
        failed=1
      fi
      pinned_pkg_names="${pinned_pkg_names}${pkg}"$'\n'
      pinned_pkg_owners="${pinned_pkg_owners}${pkg} ${list_name}"$'\n'
    done < <("$list_name")
  done

  local dupes
  dupes=$(echo "$pinned_pkg_names" | sort | uniq -d)
  if [ -n "$dupes" ]; then
    while IFS= read -r pkg; do
      [ -n "$pkg" ] || continue
      echo "PACKAGE PINNED TO MORE THAN ONE LEG: $pkg -> $(echo "$pinned_pkg_owners" | awk -v p="$pkg" '$1==p{print $2}' | paste -sd, -)"
      failed=1
    done <<<"$dupes"
  fi

  local shard_target
  for shard_target in handlers_pkg http_pkg; do
    pkg=$("$shard_target")
    if ! grep -qxF "$pkg" <<<"$actual"; then
      echo "STALE PINNED PACKAGE: $shard_target lists '$pkg', which does not exist in \`go list ./...\` (renamed or deleted?)"
      failed=1
    fi
  done

  [ "$failed" -eq 0 ] && echo "OK: every pinned root-1/2/3/core/storage-store/handlers/http package exists in go list ./... and is pinned to exactly one leg."
  return $failed
}

# assert_shard_partition_complete <pkg> <n> [filter-fn]: proves the n test-name
# shards that run_filter_for_shard (or filter-fn <shard>) builds for <pkg> run every test the package has, each in
# exactly one shard. For each shard it lists what that shard's -run regex
# selects (`go test -list`, same matching as -run), concatenates the n lists and
# compares them, as sorted multisets, with every Test*/Fuzz*/Example* name in
# the package: a name in no shard shows up as missing, a name in two shards as
# a duplicate. Example* is in the reference set on purpose: run_filter_for_shard
# selects only Test*/Fuzz*, so an Example added to a sharded package would
# otherwise silently run nowhere (the package-level `-run ""` legs do run it).
# Does not execute any test, only compiles the package, so it is cheap enough
# for the same pre-test-suite job as assert_leg_completeness. Used for
# faultops (n=2) via assert_faultops_shards_complete below.
assert_shard_partition_complete() {
  local pkg="$1" n="$2" filter_fn="${3:-run_filter_for_shard}" s filter
  local expected actual missing dupes failed=0
  expected=$(go test -list '^(Test|Fuzz|Example)' "$pkg" | grep -v '^ok\b' | sort) || return 1
  if [ -z "$expected" ]; then
    echo "SHARD PARTITION: $pkg lists no Test/Fuzz/Example names at all -- refusing to call an empty set complete"
    return 1
  fi
  actual=""
  for s in $(seq 1 "$n"); do
    if [ "$filter_fn" = run_filter_for_shard ]; then
      filter=$(run_filter_for_shard "$pkg" "$s" "$n") || return 1
    else
      filter=$("$filter_fn" "$s") || return 1
    fi
    actual+=$(go test -list "$filter" "$pkg" | grep -v '^ok\b')$'\n'
  done
  actual=$(echo "$actual" | sed '/^$/d' | sort)
  missing=$(comm -23 <(echo "$expected") <(echo "$actual" | uniq))
  dupes=$(echo "$actual" | uniq -d)
  if [ -n "$missing" ]; then
    echo "SHARD PARTITION: $pkg tests that run in NO shard (of $n):"
    echo "$missing"
    failed=1
  fi
  if [ -n "$dupes" ]; then
    echo "SHARD PARTITION: $pkg tests that run in MORE THAN ONE shard (of $n):"
    echo "$dupes"
    failed=1
  fi
  [ "$failed" -eq 0 ] && echo "OK: $pkg: all $(echo "$expected" | wc -l | tr -d ' ') Test/Fuzz/Example names run in exactly one of $n shards."
  return $failed
}

assert_faultops_shards_complete() {
  assert_shard_partition_complete "$(faultops_pkgs)" 2 faultops_run_filter
}
