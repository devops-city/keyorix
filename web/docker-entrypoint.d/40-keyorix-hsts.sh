#!/bin/sh
# Generates /etc/nginx/keyorix/nginx-hsts.conf from the environment, before nginx
# starts (nginx:alpine's entrypoint runs every executable /docker-entrypoint.d/*.sh).
#
#   KEYORIX_WEB_TRUSTED_PROXIES      comma/space separated IPs or CIDRs of the load
#                                    balancer(s)/proxies that terminate TLS in front
#                                    of this container, as nginx sees them (the TCP
#                                    peer). Should match server.http.trusted_proxies
#                                    of the backend. Default: none.
#   KEYORIX_WEB_HSTS                 auto (default) | on | off.
#                                    auto: send HSTS iff trusted proxies are set.
#                                    off: never send HSTS from this nginx.
#   KEYORIX_WEB_HSTS_MAX_AGE         seconds, default 31536000.
#   KEYORIX_WEB_HSTS_INCLUDE_SUBDOMAINS  true (default) | false.
#
# HSTS is sent ONLY for a request whose TCP peer is in the trusted set AND which
# carries X-Forwarded-Proto=https. With no trusted proxy configured nothing is
# trusted, so nothing is sent (a direct http request never gets HSTS). Any invalid
# value aborts startup rather than silently trusting more than intended.
set -eu

out=${KEYORIX_HSTS_CONF_OUT:-/etc/nginx/keyorix/nginx-hsts.conf} # override: tests only
proxies=$(printf '%s' "${KEYORIX_WEB_TRUSTED_PROXIES:-}" | tr ',' ' ')
mode=${KEYORIX_WEB_HSTS:-auto}
max_age=${KEYORIX_WEB_HSTS_MAX_AGE:-31536000}
subdomains=${KEYORIX_WEB_HSTS_INCLUDE_SUBDOMAINS:-true}

die() { echo "keyorix-hsts: $*" >&2; exit 1; }

case "$mode" in auto | on | off) ;; *) die "KEYORIX_WEB_HSTS must be auto, on or off (got '$mode')" ;; esac
case "$max_age" in '' | *[!0-9]*) die "KEYORIX_WEB_HSTS_MAX_AGE must be a number of seconds (got '$max_age')" ;; esac
case "$subdomains" in true | false) ;; *) die "KEYORIX_WEB_HSTS_INCLUDE_SUBDOMAINS must be true or false (got '$subdomains')" ;; esac

value="max-age=${max_age}"
if [ "$subdomains" = true ]; then value="${value}; includeSubDomains"; fi

cidrs=""
for p in $proxies; do
    # IPv4/IPv6 address with an optional /prefix; nothing else reaches the config.
    case "$p" in
        *[!0-9a-fA-F:./]*) die "KEYORIX_WEB_TRUSTED_PROXIES: '$p' is not an IP or CIDR" ;;
        '' | /* | */ | */*/*) die "KEYORIX_WEB_TRUSTED_PROXIES: '$p' is not an IP or CIDR" ;;
    esac
    cidrs="${cidrs}    ${p} 1;
"
done

enabled=no
if [ "$mode" != off ] && [ -n "$cidrs" ]; then enabled=yes; fi

{
    echo "# Generated by 40-keyorix-hsts.sh at container start. Do not edit."
    echo "geo \$keyorix_trusted_proxy {"
    echo "    default 0;"
    if [ "$enabled" = yes ]; then printf '%s' "$cidrs"; fi
    echo "}"
    echo "map \"\$keyorix_trusted_proxy:\$http_x_forwarded_proto\" \$keyorix_hsts {"
    echo "    default \"\";"
    if [ "$enabled" = yes ]; then echo "    \"~*^1:https\$\" \"${value}\";"; fi
    echo "}"
} > "$out"

echo "keyorix-hsts: mode=$mode trusted_proxies='${proxies:-}' hsts=$enabled"
