// Command genfaultystorage generates faulty_storage_generated.go: one explicit,
// fault-checking wrapper method per storage.Storage interface method.
//
// It deliberately does NOT embed storage.Storage in the wrapper struct. Embedding
// would let the wrapper satisfy the interface for any method it doesn't override,
// which means a fault-injection point silently does not exist for that method —
// exactly the kind of silent coverage gap this codebase's engineering practices
// call out (see CLAUDE.md, "prefer the machine-checked over the asserted"). By
// generating a full explicit implementation instead, a future addition to
// storage.Storage that this generator hasn't been rerun for makes the package
// fail to COMPILE, not silently under-cover — the ratchet is go build itself.
//
// Run via `go generate ./internal/faultstorage/` (see generate.go) whenever
// storage.Storage changes. go generate runs the command with the working
// directory set to the package directory, so paths are resolved against the
// module root (the nearest ancestor directory holding go.mod), not the cwd;
// -root overrides that. -o writes the output somewhere other than the committed
// file — internal/faultstorage/generated_fresh_test.go uses it to compare the
// committed file against a fresh run byte-for-byte.
//
// Output is deterministic for a given interface source and Go toolchain: files
// are read in os.ReadDir's sorted order, methods and imports are sorted before
// emission, and no map is iterated while writing output. (go/format's output can
// in principle change across Go releases; go.mod pins the language version.)
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	storagePkgDir  = "internal/core/storage"
	storageImport  = "github.com/keyorixhq/keyorix/internal/core/storage"
	outFile        = "internal/faultstorage/faulty_storage_generated.go"
	interfaceName  = "Storage"
	receiverName   = "w"
	ctxParamHint   = "ctx"
	generatedNotes = "Code generated by internal/faultstorage/gen; DO NOT EDIT.\n" +
		"Regenerate with: go generate ./internal/faultstorage/...\n" +
		"On a merge conflict in this file: take main's version, then regenerate. Never hand-merge it."
)

// handWritten lists Storage methods whose wrapper body needs bespoke logic (a
// callback that hands back a storage.Storage of its own, which must be re-wrapped
// so faults keep firing inside it) rather than the generic pass-through shape.
// These are implemented by hand in faultstorage.go instead of generated here.
var handWritten = map[string]bool{
	"WithTransaction": true,
}

var builtinTypes = map[string]bool{
	"string": true, "bool": true, "error": true, "byte": true, "rune": true,
	"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true,
	"uintptr": true, "float32": true, "float64": true,
	"complex64": true, "complex128": true, "any": true,
}

type field struct {
	name     string
	typ      string
	variadic bool
}

type methodInfo struct {
	name    string
	params  []field
	results []field
}

func main() {
	root := flag.String("root", "", "module root directory (default: nearest ancestor of the cwd containing go.mod)")
	out := flag.String("o", "", "output file (default: <root>/"+outFile+")")
	flag.Parse()
	if err := run(*root, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genfaultystorage:", err)
		os.Exit(1)
	}
}

// findModuleRoot walks up from dir to the first directory containing go.mod.
func findModuleRoot(dir string) (string, error) {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		} else if !errors.Is(err, os.ErrNotExist) {
			return "", err
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("no go.mod found in the working directory or any parent; pass -root")
		}
		dir = parent
	}
}

func run(root, out string) error {
	if root == "" {
		var err error
		if root, err = findModuleRoot("."); err != nil {
			return err
		}
	}
	if out == "" {
		out = filepath.Join(root, outFile)
	}
	formatted, raw, genCount, total, err := generate(root)
	if err != nil {
		if raw != nil {
			if dumpErr := os.WriteFile(out+".broken", raw, 0o600); dumpErr != nil {
				return fmt.Errorf("%w (dumping the raw source to %s.broken also failed: %w)", err, out, dumpErr)
			}
			return fmt.Errorf("%w (raw source dumped to %s.broken)", err, out)
		}
		return err
	}
	if werr := os.WriteFile(out, formatted, 0o600); werr != nil {
		return fmt.Errorf("writing %s: %w", out, werr)
	}
	fmt.Printf("genfaultystorage: wrote %d generated methods (%d hand-written, %d total) to %s\n",
		genCount, len(handWritten), total, out)
	return nil
}

// generate is the pure part of the generator: it reads the storage package
// under root and returns the gofmt'd wrapper source. It writes nothing. On a
// gofmt failure it returns the unformatted source as raw so the caller can dump
// it for debugging.
func generate(root string) (formatted, raw []byte, genCount, total int, err error) {
	fset := token.NewFileSet()
	pkgDir := filepath.Join(root, storagePkgDir)

	entries, err := os.ReadDir(pkgDir)
	if err != nil {
		return nil, nil, 0, 0, fmt.Errorf("reading %s: %w", pkgDir, err)
	}

	localTypes := map[string]bool{}
	importsByName := map[string]string{} // package identifier -> import path
	var ifaceFile *ast.File

	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		path := filepath.Join(pkgDir, e.Name())
		f, perr := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if perr != nil {
			return nil, nil, 0, 0, fmt.Errorf("parsing %s: %w", path, perr)
		}
		if e.Name() == "interface.go" {
			ifaceFile = f
		}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				localTypes[ts.Name.Name] = true
			}
		}
		for _, imp := range f.Imports {
			p := strings.Trim(imp.Path.Value, `"`)
			name := filepath.Base(p)
			if imp.Name != nil {
				name = imp.Name.Name
			}
			importsByName[name] = p
		}
	}
	if ifaceFile == nil {
		return nil, nil, 0, 0, fmt.Errorf("interface.go not found under %s", storagePkgDir)
	}

	iface, err := findInterface(ifaceFile, interfaceName)
	if err != nil {
		return nil, nil, 0, 0, err
	}

	used := map[string]bool{} // package qualifiers actually emitted, e.g. "context", "storage", "models"

	var methods []methodInfo
	for _, m := range iface.Methods.List {
		if len(m.Names) != 1 {
			return nil, nil, 0, 0, fmt.Errorf("interface method with %d names (expected 1): %v", len(m.Names), m.Names)
		}
		name := m.Names[0].Name
		ft, ok := m.Type.(*ast.FuncType)
		if !ok {
			return nil, nil, 0, 0, fmt.Errorf("method %s: expected *ast.FuncType, got %T", name, m.Type)
		}
		params, perr := extractFields(ft.Params, localTypes, used, "p")
		if perr != nil {
			return nil, nil, 0, 0, fmt.Errorf("method %s params: %w", name, perr)
		}
		results, rerr := extractFields(ft.Results, localTypes, used, "r")
		if rerr != nil {
			return nil, nil, 0, 0, fmt.Errorf("method %s results: %w", name, rerr)
		}
		methods = append(methods, methodInfo{name: name, params: params, results: results})
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].name < methods[j].name })

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// %s\n\npackage faultstorage\n\n", strings.ReplaceAll(generatedNotes, "\n", "\n// "))

	imports := buildImportBlock(used, importsByName)
	buf.WriteString(imports)
	buf.WriteString("\n")

	genCount = 0
	for _, m := range methods {
		if handWritten[m.name] {
			continue
		}
		if len(m.results) == 0 || m.results[len(m.results)-1].typ != "error" {
			return nil, nil, 0, 0, fmt.Errorf("method %s: expected last result to be error, got %v", m.name, m.results)
		}
		writeMethod(&buf, m)
		genCount++
	}

	formatted, ferr := format.Source(buf.Bytes())
	if ferr != nil {
		return nil, buf.Bytes(), 0, 0, fmt.Errorf("gofmt generated source: %w", ferr)
	}
	return formatted, nil, genCount, len(methods), nil
}

func findInterface(f *ast.File, name string) (*ast.InterfaceType, error) {
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != name {
				continue
			}
			it, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("%s is not declared as an interface type", name)
			}
			return it, nil
		}
	}
	return nil, fmt.Errorf("interface %s not found", name)
}

func extractFields(fl *ast.FieldList, local, used map[string]bool, prefix string) ([]field, error) {
	if fl == nil {
		return nil, nil
	}
	var out []field
	idx := 0
	for _, f := range fl.List {
		_, variadic := f.Type.(*ast.Ellipsis)
		typ, err := qualifyType(f.Type, local, used)
		if err != nil {
			return nil, err
		}
		if len(f.Names) == 0 {
			idx++
			out = append(out, field{name: fmt.Sprintf("%s%d", prefix, idx), typ: typ, variadic: variadic})
			continue
		}
		for _, n := range f.Names {
			idx++
			nm := n.Name
			if nm == "" || nm == "_" {
				nm = fmt.Sprintf("%s%d", prefix, idx)
			}
			out = append(out, field{name: nm, typ: typ, variadic: variadic})
		}
	}
	return out, nil
}

func qualifyType(e ast.Expr, local, used map[string]bool) (string, error) {
	switch t := e.(type) {
	case *ast.Ident:
		if builtinTypes[t.Name] {
			return t.Name, nil
		}
		if local[t.Name] {
			used["storage"] = true
			return "storage." + t.Name, nil
		}
		return "", fmt.Errorf("unqualified identifier %q is neither a builtin nor a storage-package type", t.Name)
	case *ast.SelectorExpr:
		pkgIdent, ok := t.X.(*ast.Ident)
		if !ok {
			return "", fmt.Errorf("unsupported selector base %#v", t.X)
		}
		used[pkgIdent.Name] = true
		return pkgIdent.Name + "." + t.Sel.Name, nil
	case *ast.StarExpr:
		inner, err := qualifyType(t.X, local, used)
		if err != nil {
			return "", err
		}
		return "*" + inner, nil
	case *ast.ArrayType:
		inner, err := qualifyType(t.Elt, local, used)
		if err != nil {
			return "", err
		}
		if t.Len != nil {
			return "", fmt.Errorf("fixed-size arrays are not supported in Storage signatures")
		}
		return "[]" + inner, nil
	case *ast.MapType:
		k, err := qualifyType(t.Key, local, used)
		if err != nil {
			return "", err
		}
		v, err := qualifyType(t.Value, local, used)
		if err != nil {
			return "", err
		}
		return "map[" + k + "]" + v, nil
	case *ast.Ellipsis:
		inner, err := qualifyType(t.Elt, local, used)
		if err != nil {
			return "", err
		}
		return "..." + inner, nil
	case *ast.FuncType:
		return qualifyFuncType(t, local, used)
	case *ast.InterfaceType:
		if t.Methods == nil || len(t.Methods.List) == 0 {
			return "interface{}", nil
		}
		return "", fmt.Errorf("non-empty inline interface types are not supported")
	default:
		return "", fmt.Errorf("unsupported type expression %T", e)
	}
}

func qualifyFuncType(ft *ast.FuncType, local, used map[string]bool) (string, error) {
	var params, results []string
	if ft.Params != nil {
		for _, f := range ft.Params.List {
			typ, err := qualifyType(f.Type, local, used)
			if err != nil {
				return "", err
			}
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			for i := 0; i < n; i++ {
				params = append(params, typ)
			}
		}
	}
	if ft.Results != nil {
		for _, f := range ft.Results.List {
			typ, err := qualifyType(f.Type, local, used)
			if err != nil {
				return "", err
			}
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			for i := 0; i < n; i++ {
				results = append(results, typ)
			}
		}
	}
	sig := "func(" + strings.Join(params, ", ") + ")"
	switch len(results) {
	case 0:
	case 1:
		sig += " " + results[0]
	default:
		sig += " (" + strings.Join(results, ", ") + ")"
	}
	return sig, nil
}

func buildImportBlock(used map[string]bool, importsByName map[string]string) string {
	var names []string
	for n := range used {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("import (\n")
	for _, n := range names {
		if n == "storage" {
			b.WriteString("\t\"" + storageImport + "\"\n")
			continue
		}
		path, ok := importsByName[n]
		if !ok {
			// Should not happen: every non-storage qualifier we emit came from a
			// SelectorExpr in interface.go, so it must be one of interface.go's
			// own imports. Fail loudly rather than emit unresolvable code.
			panic(fmt.Sprintf("genfaultystorage: no known import path for package qualifier %q", n))
		}
		b.WriteString("\t\"" + path + "\"\n")
	}
	b.WriteString(")\n")
	return b.String()
}

func writeMethod(buf *bytes.Buffer, m methodInfo) {
	var params []string
	for _, p := range m.params {
		t := p.typ
		if p.variadic {
			t = strings.TrimPrefix(t, "...")
			params = append(params, p.name+" ..."+t)
		} else {
			params = append(params, p.name+" "+p.typ)
		}
	}
	var resultTypes []string
	for _, r := range m.results {
		resultTypes = append(resultTypes, r.typ)
	}
	resultSig := "(" + strings.Join(resultTypes, ", ") + ")"

	var callArgs []string
	for _, p := range m.params {
		if p.variadic {
			callArgs = append(callArgs, p.name+"...")
		} else {
			callArgs = append(callArgs, p.name)
		}
	}

	nonErrResults := m.results[:len(m.results)-1]

	fmt.Fprintf(buf, "func (%s *FaultyStorage) %s(%s) %s {\n",
		receiverName, m.name, strings.Join(params, ", "), resultSig)
	fmt.Fprintf(buf, "\tfire, kind, injected := %s.check(%q)\n", receiverName, m.name)
	fmt.Fprintf(buf, "\tif fire {\n")
	fmt.Fprintf(buf, "\t\tswitch kind {\n")
	fmt.Fprintf(buf, "\t\tcase KindPanic:\n")
	fmt.Fprintf(buf, "\t\t\tpanic(injected)\n")
	fmt.Fprintf(buf, "\t\tcase KindError:\n")
	var zeroNames []string
	for i, r := range nonErrResults {
		zv := fmt.Sprintf("zero%d", i+1)
		zeroNames = append(zeroNames, zv)
		fmt.Fprintf(buf, "\t\t\tvar %s %s\n", zv, r.typ)
	}
	if len(zeroNames) > 0 {
		fmt.Fprintf(buf, "\t\t\treturn %s, injected\n", strings.Join(zeroNames, ", "))
	} else {
		fmt.Fprintf(buf, "\t\t\treturn injected\n")
	}
	fmt.Fprintf(buf, "\t\tcase KindEffectThenError:\n")
	var rvNames []string
	for i := range nonErrResults {
		rvNames = append(rvNames, fmt.Sprintf("rv%d", i+1))
	}
	call := fmt.Sprintf("%s.real.%s(%s)", receiverName, m.name, strings.Join(callArgs, ", "))
	if len(rvNames) > 0 {
		fmt.Fprintf(buf, "\t\t\t%s, _ := %s\n", strings.Join(rvNames, ", "), call)
		fmt.Fprintf(buf, "\t\t\treturn %s, injected\n", strings.Join(rvNames, ", "))
	} else {
		fmt.Fprintf(buf, "\t\t\t_ = %s\n", call)
		fmt.Fprintf(buf, "\t\t\treturn injected\n")
	}
	fmt.Fprintf(buf, "\t\t}\n")
	fmt.Fprintf(buf, "\t}\n")
	fmt.Fprintf(buf, "\treturn %s\n", call)
	fmt.Fprintf(buf, "}\n\n")
}
