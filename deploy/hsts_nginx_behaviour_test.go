// #3058: HSTS behind a TLS-terminating load balancer. These tests run a REAL nginx
// (the web image's pinned base, via docker) with the shipped config and assert the
// Strict-Transport-Security response header per request shape:
//
//	direct http, no X-Forwarded-Proto            -> no HSTS
//	trusted proxy + X-Forwarded-Proto: https     -> HSTS
//	trusted proxy + X-Forwarded-Proto: http      -> no HSTS
//	UNtrusted client + X-Forwarded-Proto: https  -> no HSTS (header never trusted)
//	no trusted proxy configured                  -> never HSTS
//	hsts off                                     -> never HSTS
//
// Trust is exercised by choosing the trusted CIDR: 0.0.0.0/0 makes the test client
// (whatever address docker NATs it to) trusted, 203.0.113.0/24 (TEST-NET-3) makes
// it untrusted. They skip when docker (or the base image) is unavailable; CI has it.

const nginxImage = "nginx:alpine@sha256:72ba65eb42c10344912a84ff42408db7d34f2feb642204570ab8fc5ffd29f1d3" // keep equal to web/Dockerfile

type hstsCase struct {
	name    string
	proxies string // KEYORIX_WEB_TRUSTED_PROXIES / web.trustedProxies, comma-separated
	mode    string // "" = default (auto)
	xfp     string // X-Forwarded-Proto sent by the client; "" = header absent
	want    bool
}

var hstsCases = []hstsCase{
	{"direct http, trusted proxy configured", "0.0.0.0/0", "", "", false},
	{"trusted proxy + https", "0.0.0.0/0", "", "https", true},
	{"trusted proxy + HTTPS (case-insensitive)", "0.0.0.0/0", "", "HTTPS", true},
	{"trusted proxy + http", "0.0.0.0/0", "", "http", false},
	{"trusted proxy + chained 'https, http'", "0.0.0.0/0", "", "https, http", false},
	{"untrusted client forging https", "203.0.113.0/24", "", "https", false},
	{"no trusted proxy configured", "", "", "https", false},
	{"hsts off", "0.0.0.0/0", "off", "https", false},
}

func needDocker(t *testing.T) {
	t.Helper()
	if _, err := exec.LookPath("docker"); err != nil {
		t.Skip("docker not installed -- skipping real-nginx HSTS check")
	}
	if err := exec.Command("docker", "image", "inspect", nginxImage).Run(); err != nil { //nolint:gosec // fixed image
		if out, err := exec.Command("docker", "pull", "-q", nginxImage).CombinedOutput(); err != nil { //nolint:gosec // fixed image
			t.Skipf("nginx base image unavailable (%v): %s", err, out)
		}
	}
}

// runNginx starts the image with the given args and returns the host port mapped to 80.
func runNginx(t *testing.T, args ...string) string {
	t.Helper()
	full := append([]string{"run", "-d", "--rm", "-p", "127.0.0.1::80"}, args...)
	out, err := exec.Command("docker", full...).CombinedOutput() //nolint:gosec // test-controlled args
	if err != nil {
		t.Fatalf("docker run: %v\n%s", err, out)
	}
	id := strings.TrimSpace(string(out))
	t.Cleanup(func() { _ = exec.Command("docker", "rm", "-f", id).Run() })     //nolint:gosec // id from docker
	pOut, err := exec.Command("docker", "port", id, "80/tcp").CombinedOutput() //nolint:gosec // id from docker
	if err != nil {
		t.Fatalf("docker port: %v\n%s", err, pOut)
	}
	hostPort := strings.TrimSpace(strings.Split(string(pOut), "\n")[0])
	base := "http://" + hostPort
	deadline := time.Now().Add(20 * time.Second)
	for time.Now().Before(deadline) {
		if resp, err := http.Get(base + "/health"); err == nil { //nolint:gosec,noctx // local test server
			_ = resp.Body.Close()
			return base
		}
		time.Sleep(200 * time.Millisecond)
	}
	logs, _ := exec.Command("docker", "logs", id).CombinedOutput() //nolint:gosec // id from docker
	t.Fatalf("nginx did not come up:\n%s", logs)
	return ""
}

func hstsHeaders(t *testing.T, base, path, xfp string) http.Header {
	t.Helper()
	req, err := http.NewRequest(http.MethodGet, base+path, nil)
	if err != nil {
		t.Fatal(err)
	}
	if xfp != "" {
		req.Header.Set("X-Forwarded-Proto", xfp)
	}
	resp, err := http.DefaultClient.Do(req) //nolint:gosec // local test server
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = resp.Body.Close() }()
	_, _ = io.Copy(io.Discard, resp.Body)
	return resp.Header
}

func assertHSTS(t *testing.T, c hstsCase, base string, paths ...string) {
	t.Helper()
	for _, p := range paths {
		got := hstsHeaders(t, base, p, c.xfp).Values("Strict-Transport-Security")
		switch {
		case c.want && (len(got) != 1 || !strings.HasPrefix(got[0], "max-age=31536000")):
			t.Errorf("%s: want exactly one HSTS (max-age=31536000...), got %q", p, got)
		case !c.want && len(got) != 0:
			t.Errorf("%s: want no HSTS, got %q", p, got)
		}
	}
}

// Compose / Docker image: web/nginx.conf + web/nginx-hsts.conf, regenerated by the
// image entrypoint script from the KEYORIX_WEB_* environment.
func TestWebNginxHSTS_ComposeImage(t *testing.T) {
	needDocker(t)
	web, err := filepath.Abs(filepath.Join("..", "web"))
	if err != nil {
		t.Fatal(err)
	}
	for i, c := range hstsCases {
		t.Run(c.name, func(t *testing.T) {
			// A private copy of the generated-conf dir: the script rewrites the file.
			dir := t.TempDir()
			def, err := os.ReadFile(filepath.Join(web, "nginx-hsts.conf")) //nolint:gosec // repo file
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(dir, "nginx-hsts.conf"), def, 0o666); err != nil { //nolint:gosec // container user must write it
				t.Fatal(err)
			}
			if err := os.Chmod(dir, 0o777); err != nil { //nolint:gosec // container user must write it
				t.Fatal(err)
			}
			args := []string{
				"--name", fmt.Sprintf("hsts3058-compose-%d-%d", os.Getpid(), i),
				"-v", filepath.Join(web, "nginx.conf") + ":/etc/nginx/nginx.conf:ro",
				// nginx.conf includes this file for the backend proxy settings (the image
				// COPYs it; a bind-mounted nginx.conf on the stock image needs it too).
				"-v", filepath.Join(web, "keyorix-backend.conf") + ":/etc/nginx/keyorix-backend.conf:ro",
				"-v", dir + ":/etc/nginx/keyorix",
				"-v", filepath.Join(web, "docker-entrypoint.d", "40-keyorix-hsts.sh") + ":/docker-entrypoint.d/40-keyorix-hsts.sh:ro",
				"-e", "KEYORIX_WEB_TRUSTED_PROXIES=" + c.proxies,
			}
			if c.mode != "" {
				args = append(args, "-e", "KEYORIX_WEB_HSTS="+c.mode)
			}
			base := runNginx(t, append(args, nginxImage)...)
			assertHSTS(t, c, base, "/health", "/", "/missing.js") // server scope, SPA, static-asset location
		})
	}
}

// writeTestCA generates a throwaway self-signed CA certificate (PEM) in a temp dir and
// returns its path, readable by the nginx container user.
func writeTestCA(t *testing.T) string {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	tmpl := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: "keyorix-hsts-test-ca"},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(24 * time.Hour),
		IsCA:                  true,
		BasicConstraintsValid: true,
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "ca.crt")
	if err := os.WriteFile(path, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil { //nolint:gosec // public cert, read by the container
		t.Fatal(err)
	}
	return path
}

// Helm chart: the nginx.conf inside the rendered web ConfigMap.
func TestWebNginxHSTS_HelmChart(t *testing.T) {
	needDocker(t)
	if _, err := exec.LookPath("helm"); err != nil {
		t.Skip("helm not installed -- skipping chart web-config check")
	}
	chart := filepath.Join("..", "deploy", "helm", "keyorix")
	caFile := writeTestCA(t)
	for i, c := range hstsCases {
		t.Run(c.name, func(t *testing.T) {
			sets := []string{"--set", "web.enabled=true", "--set", "auth.masterPassword=x", "--set", "postgresql.auth.password=x"}
			if c.proxies != "" {
				sets = append(sets, "--set", "web.trustedProxies={"+c.proxies+"}")
			}
			if c.mode != "" {
				sets = append(sets, "--set", "web.hsts.mode="+c.mode)
			}
			args := append([]string{"template", "kx", chart, "-s", "templates/web-config.yaml"}, sets...)
			out, err := exec.Command("helm", args...).CombinedOutput() //nolint:gosec // fixed binary, test-controlled args
			if err != nil {
				t.Fatalf("helm template: %v\n%s", err, out)
			}
			var cm struct {
				Data map[string]string `yaml:"data"`
			}
			if err := yaml.Unmarshal(out, &cm); err != nil || cm.Data["nginx.conf"] == "" {
				t.Fatalf("no nginx.conf in rendered ConfigMap (%v):\n%s", err, out)
			}
			conf := filepath.Join(t.TempDir(), "nginx.conf")
			if err := os.WriteFile(conf, []byte(cm.Data["nginx.conf"]), 0o644); err != nil { //nolint:gosec // read by the container
				t.Fatal(err)
			}
			base := runNginx(t,
				"--name", fmt.Sprintf("hsts3058-helm-%d-%d", os.Getpid(), i),
				"--add-host", "kx-keyorix-server:127.0.0.1", // literal proxy_pass host must resolve; nothing listens (502)
				"-v", conf+":/etc/nginx/nginx.conf:ro",
				// The secure-baseline web config verifies the backend against this CA
				// (proxy_ssl_trusted_certificate); nginx will not start without the file.
				"-v", caFile+":/etc/keyorix/tls/ca.crt:ro",
				nginxImage)
			assertHSTS(t, c, base, "/health", "/", "/missing.js", "/api/v1/x") // incl. the proxied (502) API location
		})
	}
}

// The entrypoint script writes untrusted-ish text into nginx config, so it must
// refuse anything that is not an IP/CIDR (no config injection) and bad modes.
func TestWebNginxHSTS_EntrypointRejectsBadInput(t *testing.T) {
	script, err := filepath.Abs(filepath.Join("..", "web", "docker-entrypoint.d", "40-keyorix-hsts.sh"))
	if err != nil {
		t.Fatal(err)
	}
	for name, env := range map[string][]string{
		"config injection":  {"KEYORIX_WEB_TRUSTED_PROXIES=10.0.0.1 1; } server { listen 81; "},
		"semicolon":         {"KEYORIX_WEB_TRUSTED_PROXIES=10.0.0.1;"},
		"hostname":          {"KEYORIX_WEB_TRUSTED_PROXIES=lb.example.com"},
		"bad mode":          {"KEYORIX_WEB_TRUSTED_PROXIES=10.0.0.1", "KEYORIX_WEB_HSTS=maybe"},
		"non-numeric age":   {"KEYORIX_WEB_TRUSTED_PROXIES=10.0.0.1", "KEYORIX_WEB_HSTS_MAX_AGE=1;x"},
		"bad subdomains":    {"KEYORIX_WEB_TRUSTED_PROXIES=10.0.0.1", "KEYORIX_WEB_HSTS_INCLUDE_SUBDOMAINS=yes"},
		"double slash cidr": {"KEYORIX_WEB_TRUSTED_PROXIES=10.0.0.0/8/8"},
	} {
		t.Run(name, func(t *testing.T) {
			outFile := filepath.Join(t.TempDir(), "hsts.conf")
			cmd := exec.Command("sh", script) //nolint:gosec // repo script
			cmd.Env = append([]string{"PATH=" + os.Getenv("PATH"), "KEYORIX_HSTS_CONF_OUT=" + outFile}, env...)
			if out, err := cmd.CombinedOutput(); err == nil {
				t.Fatalf("script accepted bad input, output:\n%s", out)
			}
			if _, err := os.Stat(outFile); err == nil {
				t.Error("script wrote a config despite rejecting its input")
			}
		})
	}
}

func TestWebNginxHSTS_HelmRejectsBadValues(t *testing.T) {
	if _, err := exec.LookPath("helm"); err != nil {
		t.Skip("helm not installed")
	}
	chart := filepath.Join("..", "deploy", "helm", "keyorix")
	base := []string{"template", "kx", chart, "-s", "templates/web-config.yaml",
		"--set", "web.enabled=true", "--set", "auth.masterPassword=x", "--set", "postgresql.auth.password=x"}
	for name, extra := range map[string][]string{
		"injection in proxy": {"--set", "web.trustedProxies={10.0.0.1;}"},
		"mode on, no proxy":  {"--set", "web.hsts.mode=on"},
		"bad mode":           {"--set", "web.hsts.mode=maybe"},
	} {
		t.Run(name, func(t *testing.T) {
			if out, err := exec.Command("helm", append(append([]string{}, base...), extra...)...).CombinedOutput(); err == nil { //nolint:gosec // fixed binary
				t.Fatalf("helm rendered despite bad values:\n%s", out)
			}
		})
	}
}
